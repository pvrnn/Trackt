export type Brand = keyof typeof BRANDS;

export function brandTitle(brand: Brand): string {
  return BRANDS[brand].title;
}

/** The bare mark in `currentColor`. Decorative: the brand's name is always written beside it. */
export function BrandMark({ brand, className }: { brand: Brand; className?: string }) {
  return (
    <svg aria-hidden viewBox="0 0 24 24" fill="currentColor" className={className}>
      <path d={BRANDS[brand].path} />
    </svg>
  );
}

/** The mark on the brand's own colour (white unless the brand sets an ink), as an app-icon tile. */
export function BrandTile({ brand, className }: { brand: Brand; className?: string }) {
  const def = BRANDS[brand];
  return (
    <span
      aria-hidden
      className={clsx(
        'flex shrink-0 items-center justify-center text-white shadow-[inset_0_0_0_1px_rgb(255_255_255/0.12)]',
        className,
      )}
      style={{ backgroundColor: def.color, color: 'ink' in def ? def.ink : undefined }}
    >
      <BrandMark brand={brand} className="size-[52%]" />
    </span>
  );
}
